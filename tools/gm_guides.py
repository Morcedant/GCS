"""The GM's Guides, kept out of the pages: only registered GMs get them, from the table server.

A game's build writes its GM's Guide to <game folder>/gm-guide.json and puts an empty, locked book in the page;
bundle() gathers every game's gm-guide.json into legend-dynamics/table-server/src/gm-guides.js, which the
server hands out to a GM whose access code checks out (POST /api/gm/guide). Grimm's guide comes from the
claude/grimm-wild-west branch, where Grimm is built (tools/fan_sources.py).

  python3 tools/gm_guides.py      rebuild the server's bundle from the gm-guide.json files
"""
import html
import json
from pathlib import Path

import fan_sources

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "legend-dynamics" / "table-server" / "src" / "gm-guides.js"
# game id (as the pages name it to the table server) → its folder
GAMES = {"western": "legend-dynamics/western", "spaceopera": "legend-dynamics/spaceopera", "aurora": "legend-dynamics/aurora",
         "fantasy": "legend-dynamics/fantasy", "uss-pelion": "uss-pelion", "grimm-west": "grimm-west"}


def locked_book(title, subtitle):
    """The GM's Guide's place in the page: empty until a registered GM unlocks it."""
    return (f'<div class="guide-book" id="guide-gm" data-title="{html.escape(title)}" data-subtitle="{html.escape(subtitle)}" data-locked="1" hidden>\n'
            "</div>\n")


def write_game(folder, title, subtitle, body):
    (Path(folder) / "gm-guide.json").write_text(json.dumps({"title": title, "subtitle": subtitle, "html": body}, ensure_ascii=False) + "\n")


def _read(game):
    try:
        return json.loads(fan_sources.read_text(f"{GAMES[game]}/gm-guide.json"))
    except FileNotFoundError:
        return None


def bundle():
    """Write the server's bundle; nothing to do on a branch without the table server."""
    if not SERVER.parent.exists():
        return
    guides = {g: d for g in GAMES if (d := _read(g))}
    SERVER.write_text("// Generated by tools/gm_guides.py from each game's gm-guide.json: don't edit by hand.\n"
                      "// The GM's Guides, sent only to registered GMs (POST /api/gm/guide).\n"
                      "export default " + json.dumps(guides, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"wrote {SERVER.relative_to(ROOT)} ({', '.join(guides)})")


if __name__ == "__main__":
    bundle()
