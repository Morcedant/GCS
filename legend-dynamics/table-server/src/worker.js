// @ts-check
/**
 * Legend Dynamics shared table: a Cloudflare Worker with one Durable Object per table.
 *
 *   POST /api/tables              { name, game, access? }  → { code, gmKey, name }   start a table (the GM keeps the key)
 *   GET  /api/tables/CODE                         → { name, game, players }  does it exist, and what is it
 *   GET  /api/tables/CODE/ws      WebSocket: the table's live connection (see table.js for the messages)
 *   POST /api/gm                  { access }        → { name }                  is this a registered GM (opens the GM view)
 *   POST /api/gm/guide            { access, game }  → { title, subtitle, html }  a game's GM's Guide, for registered GMs only
 *   GET  /api/blog?tag=            → { posts, tags }        the dev blog's published posts, newest first (blog.js)
 *   GET  /api/blog/ID              → { post }               one post
 *   POST /api/blog/admin           { access, action: "list" | "get" | "save" | "delete", id?, post? }   an author only (the DEV secret)
 *   POST /api/feedback             { feedback }            → { ok }  playtest feedback from the site, from anyone (a few an hour each)
 *   POST /api/feedback/admin       { access, action: "list" | "delete", id? }   an author only: read it, or delete one
 *
 * ALLOWED_ORIGINS (a var in wrangler.toml) lists the sites whose pages may connect, comma-separated, or "*".
 * GM_CODES (a secret, set in the Cloudflare dashboard) lists the GMs who may start tables: "Name: code", one per line
 * or comma. While it's empty, anyone may start one. Joining an existing table only ever needs that table's code.
 * The GM's Guides (src/gm-guides.js, generated by tools/gm-guides.py) are not in the pages: this server hands them out.
 */
import { newCode, validCode, hashKey, parseAccess, checkAccess } from "./logic.js";
export { Table } from "./table.js";
import GM_GUIDES from "./gm-guides.js";
import { BLOG_NAME } from "./blog.js";

/** Who may write the blog: a code in the DEV secret (a bare code, or "Name: code" lines), its own codes, not the GMs'.
 * Null for anyone else. @param {any} env @param {any} code */
async function blogAuthor(env, code) {
  const authors = parseAccess(env.DEV).map((a) => (a.name === "GM" ? { ...a, name: "DEV" } : a)); // a bare code is "DEV"
  return authors.length ? checkAccess(authors, code) : null; // no DEV secret, no writing
}

/** @param {any} env @param {string} origin */
const originOk = (env, origin) => {
  const list = String(env.ALLOWED_ORIGINS || "*").split(",").map((s) => s.trim()).filter(Boolean);
  return list.includes("*") || !origin || list.includes(origin) || (origin === "null" && list.includes("null"));
};
/** @param {any} env @param {string} origin */
const cors = (env, origin) => ({
  "Access-Control-Allow-Origin": originOk(env, origin) ? origin || "*" : "null",
  "Access-Control-Allow-Methods": "GET, POST, OPTIONS", "Access-Control-Allow-Headers": "Content-Type", "Vary": "Origin",
});
/** @param {any} body @param {number} status @param {Record<string, string>} headers */
const json = (body, status, headers) => new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json", ...headers } });

const randomInt = (/** @type {number} */ n) => { const b = new Uint32Array(1); crypto.getRandomValues(b); return b[0] % n; };
const newKey = () => { const b = new Uint8Array(24); crypto.getRandomValues(b); return btoa(String.fromCharCode(...b)).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, ""); };

export default {
  /** @param {Request} req @param {any} env */
  async fetch(req, env) {
    const url = new URL(req.url), origin = req.headers.get("Origin") || "", h = cors(env, origin);
    if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: h });
    if (!originOk(env, origin)) return json({ error: "This site isn't allowed to use the table server." }, 403, h);
    if (url.pathname === "/") return new Response("Legend Dynamics table server. Start or join a table from a character creator.", { headers: { "Content-Type": "text/plain", ...h } });

    if (url.pathname === "/api/tables" && req.method === "POST") {
      /** @type {any} */ let body = {};
      try { body = await req.json(); } catch { /* an empty body is fine */ }
      const access = parseAccess(env.GM_CODES);
      let by = "";
      if (access.length) {
        const who = await checkAccess(access, body.access);
        if (who === null) return json({ error: body.access ? "That GM access code isn't recognised" : "This table server needs a GM access code to start a table", access: true }, 401, h);
        by = who;
      }
      const gmKey = newKey(), gmKeyHash = await hashKey(gmKey);
      for (let i = 0; i < 5; i++) { // a code already in use is tried again
        const code = newCode(randomInt);
        const stub = env.TABLES.get(env.TABLES.idFromName(code));
        const r = await stub.fetch("https://table/init", { method: "POST", body: JSON.stringify({ name: body.name, game: body.game, gmKeyHash }) });
        if (r.ok) {
          const t = /** @type {any} */ (await r.json());
          console.log(`table ${code} started${by ? ` by ${by}` : ""}`); // in the Worker's logs
          return json({ code, gmKey, name: t.name }, 201, h);
        }
        if (r.status !== 409) return json({ error: "The table couldn't be started." }, 500, h);
      }
      return json({ error: "No free table code: try again." }, 503, h);
    }

    if ((url.pathname === "/api/gm" || url.pathname === "/api/gm/guide") && req.method === "POST") {
      /** @type {any} */ let body = {};
      try { body = await req.json(); } catch { /* an empty body is refused below */ }
      const access = parseAccess(env.GM_CODES);
      const who = access.length ? await checkAccess(access, body.access) : "GM";
      if (who === null) return json({ error: body.access ? "That GM access code isn't recognised" : "The GM view needs a GM access code", access: true }, 401, h);
      if (url.pathname === "/api/gm") return json({ name: who }, 200, h);
      const guide = Object.prototype.hasOwnProperty.call(GM_GUIDES, body.game) ? GM_GUIDES[body.game] : null;
      if (!guide) return json({ error: "This server has no GM's Guide for that game." }, 404, h);
      return json(guide, 200, { ...h, "Cache-Control": "no-store" });
    }

    // The dev blog: anyone reads; an author writes.
    if (url.pathname === "/api/blog" || url.pathname.startsWith("/api/blog/")) {
      const stub = env.TABLES.get(env.TABLES.idFromName(BLOG_NAME)), pass = async (/** @type {string} */ p, /** @type {any} */ init) => {
        const r = await stub.fetch("https://table" + p, init); return json(await r.json(), r.status, { ...h, "Cache-Control": "no-store" }); };
      if (url.pathname === "/api/blog" && req.method === "GET") return pass(`/blog/list?tag=${encodeURIComponent(url.searchParams.get("tag") || "")}`);
      if (url.pathname === "/api/blog/admin" && req.method === "POST") {
        /** @type {any} */ let body = {};
        try { body = await req.json(); } catch { /* refused below */ }
        const author = await blogAuthor(env, body.access);
        if (!author) return json({ error: body.access ? "That code can't write the blog." : "Writing the blog needs the author's code.", access: true }, 401, h);
        if (body.action === "list") return pass("/blog/list?drafts=1");
        if (body.action === "get") return pass(`/blog/get?drafts=1&id=${encodeURIComponent(body.id || "")}`);
        if (body.action === "save") return pass("/blog/save", { method: "POST", body: JSON.stringify({ post: body.post, author }) });
        if (body.action === "delete") return pass("/blog/delete", { method: "POST", body: JSON.stringify({ id: body.id }) });
        return json({ error: "Unknown action." }, 400, h);
      }
      const one = url.pathname.match(/^\/api\/blog\/([a-z0-9-]{1,80})$/);
      if (one && req.method === "GET") return pass(`/blog/get?id=${one[1]}`);
      return json({ error: "Not found." }, 404, h);
    }

    // Playtest feedback: anyone sends it; an author (the DEV secret) reads it.
    if ((url.pathname === "/api/feedback" || url.pathname === "/api/feedback/admin") && req.method === "POST") {
      const stub = env.TABLES.get(env.TABLES.idFromName(BLOG_NAME)), pass = async (/** @type {string} */ p, /** @type {any} */ init) => {
        const r = await stub.fetch("https://table" + p, init); return json(await r.json(), r.status, { ...h, "Cache-Control": "no-store" }); };
      /** @type {any} */ let body = {};
      try { body = await req.json(); } catch { /* refused below */ }
      if (url.pathname === "/api/feedback") {
        if (body.website) return json({ ok: true }, 200, h); // the form's hidden field: only a robot fills it in
        const sender = await hashKey(String(req.headers.get("CF-Connecting-IP") || "") + "|feedback");
        return pass("/feedback/add", { method: "POST", body: JSON.stringify({ feedback: body.feedback, sender }) });
      }
      const author = await blogAuthor(env, body.access);
      if (!author) return json({ error: body.access ? "That code can't read the feedback." : "Reading the feedback needs the author's code.", access: true }, 401, h);
      if (body.action === "list") return pass("/feedback/list");
      if (body.action === "delete") return pass("/feedback/delete", { method: "POST", body: JSON.stringify({ id: body.id }) });
      return json({ error: "Unknown action." }, 400, h);
    }

    const m = url.pathname.match(/^\/api\/tables\/([^/]+)(\/ws)?$/);
    if (m && req.method === "GET") {
      const code = decodeURIComponent(m[1]).toUpperCase();
      if (!validCode(code)) return json({ error: "That isn't a table code." }, 400, h);
      const stub = env.TABLES.get(env.TABLES.idFromName(code));
      if (m[2]) {
        if (req.headers.get("Upgrade") !== "websocket") return json({ error: "Connect with a WebSocket." }, 426, h);
        return stub.fetch(new Request("https://table/ws", req));
      }
      const r = await stub.fetch("https://table/info");
      return json(await r.json(), r.status, h);
    }
    return json({ error: "Not found." }, 404, h);
  },
};
